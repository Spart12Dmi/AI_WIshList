"""python -m evals.benchmark [--models llama3.2:3b qwen3:4b] [--strict]

Offline rules by default. Models are called locally, never downloaded implicitly.
Labels are hand-authored, not generated by the matcher being evaluated.
"""

import argparse
import hashlib
import json
import statistics
import time
from collections import defaultdict
from datetime import datetime, timezone
from itertools import product
from pathlib import Path

import httpx
from pydantic import BaseModel, ConfigDict, Field

from app.agents import SemanticValidationAgent
from app.config import get_settings
from app.matching import is_individual_product_url
from app.regions import get_region
from app.schemas import ProductOffer

CORPUS = Path(__file__).with_name("search_cases.json")
CORPORA = [
    CORPUS,
    CORPUS.with_name("observed_cases.json"),
    CORPUS.with_name("extended_cases.json"),
    CORPUS.with_name("intent_cases.json"),
    CORPUS.with_name("universal_cases.json"),
]


class Case(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)
    id: str
    split: str
    query: str
    title: str
    relevant: bool
    expected: bool
    reason: str
    provenance: str = "synthetic-boundary-case"
    category: str = "uncategorized"
    region: str = "czechia"
    url: str | None = None
    currency: str = "CZK"
    price: float | None = 1500.0
    availability: str | None = "InStock"
    # Optional output captured from an independent planner/reviewer run. The
    # deterministic benchmark leaves this empty; translated fixtures can
    # provide a reviewed phrase without putting a synonym table in app code.
    variants: list[str] = Field(default_factory=list, max_length=4)

    def offer(self):
        return {
            "title": self.title,
            "url": self.url or f"https://example.cz/{self.id}",
            "shop": "Evaluation fixture (not a live offer)",
            "price": self.price,
            "currency": self.currency,
            "availability": self.availability,
        }


def load_cases(path=CORPUS):
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    cases = [Case.model_validate(item) for item in data["cases"]]
    if len({case.id for case in cases}) != len(cases):
        raise ValueError("Evaluation IDs must be unique")
    return cases


def available(offer):
    # Kept aligned with catalogue minima; tested separately against catalogue output.
    from app.catalog import is_available

    return is_available(offer.get("availability"))


def decision(case, assessment=None):
    try:
        offer = ProductOffer.model_validate(case.offer()).model_dump()
    except ValueError:
        return False
    return bool(
        offer["currency"]
        and is_individual_product_url(offer["url"])
        and available(offer)
        and SemanticValidationAgent().accepts(
            offer, case.query, get_region(case.region), assessment, case.variants
        )
    )


def metrics(rows, field="predicted", label="expected"):
    tp = sum(r[field] is True and r[label] for r in rows)
    fp = sum(r[field] is True and not r[label] for r in rows)
    fn = sum(r[field] is not True and r[label] for r in rows)
    tn = sum(r[field] is False and not r[label] for r in rows)
    invalid = sum(r[field] is None for r in rows)
    precision = tp / (tp + fp) if tp + fp else None
    recall = tp / (tp + fn) if tp + fn else None
    return {
        "count": len(rows),
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "tn": tn,
        "invalid": invalid,
        "precision": precision,
        "recall": recall,
        "f1": 2 * tp / (2 * tp + fp + fn) if 2 * tp + fp + fn else None,
        "accuracy": (tp + tn) / len(rows) if rows else None,
    }


def run(cases, models, repeat=1):
    agent = SemanticValidationAgent()
    report = {"checked_at": datetime.now(timezone.utc).isoformat(), "runs": {}}
    rules = [{**case.model_dump(), "predicted": decision(case)} for case in cases]
    report["runs"]["rules"] = {"rows": rules}
    if models:
        settings = get_settings()
        tags = httpx.get(settings.ollama_base_url.rstrip("/") + "/api/tags", timeout=5)
        tags.raise_for_status()
        installed = {item["name"]: item for item in tags.json()["models"]}
        report["inference"] = {"context_tokens": settings.llm_context_tokens, "seed": 42, "thinking": False}
        # One candidate per invocation: matches the streaming app and preserves
        # candidate-level latency/errors instead of hiding them in large batches.
        for model in models:
            if model not in installed:
                report["runs"][model] = {"error": "Model not installed; no download or fallback performed"}
                continue
            rows = []
            for repetition, case in product(range(1, repeat + 1), cases):
                started = time.monotonic()
                row = {**case.model_dump(), "predicted": None, "raw_relevant": None, "repeat": repetition}
                try:
                    assessment = agent.assess(
                        [case.offer()], case.query, get_region(case.region), model, case.variants
                    )[
                        case.offer()["url"]
                    ]
                    row.update(
                        predicted=decision(case, assessment),
                        raw_relevant=assessment[0],
                        raw_region_match=assessment[1],
                        confidence=assessment[2],
                        model_reason=agent.last_reasons.get(case.offer()["url"]),
                    )
                except Exception as exc:
                    row["error"] = type(exc).__name__ + ": " + str(exc)[:300]
                row["seconds"] = round(time.monotonic() - started, 3)
                rows.append(row)
                print(
                    f"{model}: {case.id}: {row['predicted']} expected={case.expected} {row['seconds']}s",
                    flush=True,
                )
            report["runs"][model] = {"rows": rows, "model_metadata": installed[model]}
    for result in report["runs"].values():
        if "rows" not in result:
            continue
        rows = result["rows"]
        result["metrics"] = metrics(rows)
        groups = defaultdict(list)
        for row in rows:
            groups[row["split"]].append(row)
        result["by_split"] = {split: metrics(items) for split, items in groups.items()}
        categories = defaultdict(list)
        for row in rows:
            categories[row.get("category", "uncategorized")].append(row)
        result["by_category"] = {
            category: metrics(items) for category, items in sorted(categories.items())
        }
        result["errors"] = [row["id"] for row in rows if row["predicted"] != row["expected"]]
        if rows and "raw_relevant" in rows[0]:
            result["raw_relevance_metrics"] = metrics(rows, "raw_relevant", "relevant")
            result["median_seconds"] = statistics.median(row["seconds"] for row in rows)
            predictions = defaultdict(list)
            for row in rows:
                predictions[row["id"]].append(row["predicted"])
            repeated = {key: values for key, values in predictions.items() if len(values) > 1}
            result["consistency"] = {
                "repeated_cases": len(repeated),
                "changed_decisions": [key for key, values in repeated.items() if len(set(values)) > 1],
            }
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", type=Path, nargs="+", default=CORPORA)
    parser.add_argument("--models", nargs="*", default=[])
    parser.add_argument("--repeat", type=int, choices=range(1, 6), default=1)
    parser.add_argument("--split", choices=["regression", "challenge", "all"], default="all")
    parser.add_argument("--output", type=Path)
    parser.add_argument(
        "--strict", action="store_true", help="Nonzero exit for any misclassification or model error"
    )
    args = parser.parse_args()
    cases = [
        case
        for path in args.dataset
        for case in load_cases(path)
        if args.split == "all" or case.split == args.split
    ]
    if len({case.id for case in cases}) != len(cases):
        parser.error("Case IDs must be unique across the selected datasets")
    report = run(cases, args.models, args.repeat)
    report["dataset_sha256"] = {
        str(path): hashlib.sha256(path.read_bytes()).hexdigest() for path in args.dataset
    }
    root = Path(__file__).resolve().parent.parent
    report["code_sha256"] = {
        str(path.relative_to(root)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in [root / "app/agents.py", root / "app/matching.py", root / "app/catalog.py"]
    }
    output = args.output or Path("data/evaluations") / (
        datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ") + "-benchmark.json"
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    failed = False
    for name, result in report["runs"].items():
        print(name, json.dumps(result.get("metrics", result), ensure_ascii=False))
        if result.get("errors"):
            print("  Errors:", ", ".join(result["errors"]))
        failed |= bool(result.get("error") or result.get("errors"))
    print("Report:", output)
    return 1 if args.strict and failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
